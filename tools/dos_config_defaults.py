#!/usr/bin/env python3
"""dos_config_defaults.py: the game's settings (ChupathingyCE's
port/linux/src/port_config.c table: each setting's name, type and default)
as a C table for the DOS and Windows 95 builds, which answer the game's
config_boolean, config_integer, config_real and config_string from their own
settings file over these defaults (port/dos/game/dos_config.c).

    python tools/dos_config_defaults.py

Writes port/dos/game/dos_config_defaults_generated.c. A default that is a
macro (DEFAULT_ANTI_ALIASING...) is taken as the empty string, false or 0.
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "chupathingyce/port/linux/src/port_config.c"
OUTPUT = ROOT / "port/dos/game/dos_config_defaults_generated.c"

ENTRY = re.compile(r'\{\s*"([a-z0-9_.]+)",\s*_config_(boolean|integer|real|string),\s*("(?:[^"\\]|\\.)*"|[A-Z_][A-Z0-9_]*)')
TYPES = {"boolean": 0, "integer": 1, "real": 2, "string": 3}


def main():
    text = SOURCE.read_text(encoding="utf-8", errors="replace")
    entries = []
    seen = set()
    for name, kind, default in ENTRY.findall(text):
        if name in seen:
            continue
        seen.add(name)
        if not default.startswith('"'):
            default = '""'
        entries.append((name, TYPES[kind], default))
    lines = [
        "/* generated by tools/dos_config_defaults.py - do not edit: the game's",
        "settings and their defaults (chupathingyce/port/linux/src/port_config.c) */",
        "",
        "#include \"dos_config.h\"",
        "",
        "const struct dos_config_default dos_config_defaults[] =",
        "{",
    ]
    lines += [f'\t{{ "{name}", {kind}, {default} }},' for name, kind, default in entries]
    lines += ["};", "", f"const int dos_config_default_count = {len(entries)};", ""]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(entries)} settings")


if __name__ == "__main__":
    main()
